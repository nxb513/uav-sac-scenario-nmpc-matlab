function [feature, parts] = targeted_causal_feature_from_trajectory( ...
        X, UApplied, reference, currentStep, sampleTime, nominalPlant)
%TARGETED_CAUSAL_FEATURE_FROM_TRAJECTORY Build causal feature v2 at one step.
%
% X(:,currentStep) is the current state. UApplied(:,currentStep-1) is the
% most recently applied input. Only reference(:,currentStep:currentStep+20)
% is exposed, because the commanded reference preview is known online.

validateattributes(currentStep, {'numeric'}, ...
    {'scalar', 'integer', '>=', 5});
validateattributes(sampleTime, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'positive'});
if size(X, 1) ~= 12 || size(UApplied, 1) ~= 4 || ...
        size(reference, 1) ~= 12
    error('targeted_causal_feature_from_trajectory:BadShape', ...
        'X/reference must have 12 rows and UApplied must have four rows.');
end
if currentStep > size(X, 2) || currentStep - 1 > size(UApplied, 2)
    error('targeted_causal_feature_from_trajectory:MissingHistory', ...
        'The trajectory does not contain the requested causal history.');
end
if currentStep + 20 > size(reference, 2)
    error('targeted_causal_feature_from_trajectory:MissingPreview', ...
        'The reference does not contain k:k+20.');
end

stateHistory = X(:, currentStep - 3:currentStep);
inputHistory = UApplied(:, currentStep - 4:currentStep - 1);
referenceLookahead = reference(:, currentStep:currentStep + 20);
predictionTime = (currentStep - 2) * sampleTime;
nominalPrediction = quad_step_rk4(predictionTime, ...
    X(:, currentStep - 1), UApplied(:, currentStep - 1), ...
    sampleTime, nominalPlant, []);
predictionResidual = quad_state_prediction_error( ...
    X(:, currentStep), nominalPrediction);

feature = targeted_surrogate_build_feature(stateHistory, inputHistory, ...
    referenceLookahead, predictionResidual);
parts = struct('StateHistory', stateHistory, ...
    'InputHistory', inputHistory, ...
    'ReferenceLookahead', referenceLookahead, ...
    'PredictionResidual', predictionResidual, ...
    'NominalPrediction', nominalPrediction, ...
    'CurrentStep', currentStep, 'FeatureVersion', 'causal_feature_v2');
end
