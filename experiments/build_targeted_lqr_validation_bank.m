function build_targeted_lqr_validation_bank()
%BUILD_TARGETED_LQR_VALIDATION_BANK Freeze the balanced LQR-screen bank.

projectRoot = fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(projectRoot, 'configs'));
addpath(genpath(fullfile(projectRoot, 'src')));
cfg = targeted_lqr_weak_config();
disturbanceCfg = step3_disturbance_config();
outputRoot = fullfile(projectRoot, cfg.resultRoot, ...
    cfg.screenBenchmark.bankOutputSubfolder);
if ~isfolder(outputRoot)
    mkdir(outputRoot);
end

clock = tic;
[bank, manifest] = quad_build_balanced_targeted_bank(cfg, ...
    disturbanceCfg, cfg.screenBenchmark.replicatesPerCell, ...
    cfg.screenBenchmark.seed);
wallSeconds = toc(clock);
writetable(manifest, fullfile(outputRoot, ...
    'validation_bank_manifest.csv'));
save(fullfile(outputRoot, 'validation_bank.mat'), 'bank', 'manifest', ...
    'cfg', 'wallSeconds', '-v7.3');
write_report(outputRoot, cfg, manifest, wallSeconds);
write_text(fullfile(outputRoot, 'COMPLETED.txt'), sprintf( ...
    ['task=build_targeted_lqr_validation_bank\ncompleted_at=%s\n' ...
    'episode_count=%d\ncell_count=%d\nreplicates_per_cell=%d\n' ...
    'seed=%d\nwall_seconds=%.6f\nuncertainty_domain=targeted\n' ...
    'disturbance_domain=train\n'], ...
    char(datetime('now', 'TimeZone', 'local', 'Format', ...
    'yyyy-MM-dd HH:mm:ss.SSSXXX')), height(manifest), ...
    numel(unique(manifest.CellId)), ...
    cfg.screenBenchmark.replicatesPerCell, cfg.screenBenchmark.seed, ...
    wallSeconds));
end

function write_report(outputRoot, cfg, manifest, wallSeconds)
path = fullfile(outputRoot, 'validation_bank_report.md');
fileId = fopen(path, 'w');
assert(fileId >= 0, 'Cannot open %s.', path);
cleanup = onCleanup(@() fclose(fileId));
fprintf(fileId, '# Balanced targeted LQR validation bank\n\n');
fprintf(fileId, '- Episodes: %d.\n', height(manifest));
fprintf(fileId, '- Full-factorial cells: %d.\n', ...
    numel(unique(manifest.CellId)));
fprintf(fileId, '- Replicates per cell: %d.\n', ...
    cfg.screenBenchmark.replicatesPerCell);
fprintf(fileId, '- Seed: `%d`.\n', cfg.screenBenchmark.seed);
fprintf(fileId, '- Uncertainty domain: `targeted` (ID).\n');
fprintf(fileId, '- Disturbance domain: `train`.\n');
fprintf(fileId, '- Wall time: %.6f s.\n', wallSeconds);
fprintf(fileId, '- Peak speed range: %.3f to %.3f m/s.\n', ...
    min(manifest.PeakReferenceSpeed), max(manifest.PeakReferenceSpeed));
fprintf(fileId, '- Peak acceleration range: %.3f to %.3f m/s^2.\n', ...
    min(manifest.PeakReferenceAcceleration), ...
    max(manifest.PeakReferenceAcceleration));
fprintf(fileId, '- Peak nominal feedforward-bound fraction: %.3f.\n', ...
    max(manifest.PeakFeedforwardFraction));
speedError = abs(manifest.PeakReferenceSpeed - ...
    manifest.TargetReferenceSpeed) ./ manifest.TargetReferenceSpeed;
accelerationError = abs(manifest.PeakReferenceAcceleration - ...
    manifest.TargetReferenceAcceleration) ./ ...
    manifest.TargetReferenceAcceleration;
fprintf(fileId, '- Maximum realized-speed error: %.3f%%.\n', ...
    100 * max(speedError));
fprintf(fileId, '- Maximum realized-acceleration error: %.3f%%.\n', ...
    100 * max(accelerationError));
fprintf(fileId, '- Maximum reference/X0 state violation: %.3g / %.3g.\n', ...
    max(manifest.ReferenceStateBoundViolation), ...
    max(manifest.InitialStateBoundViolation));
fprintf(fileId, ['\nThe row order is randomized after explicitly crossing all ' ...
    'reference, disturbance and uncertainty factors. Test/OOD data remain ' ...
    'locked and are not used to construct this bank.\n']);
clear cleanup;
end

function write_text(path, content)
fileId = fopen(path, 'w');
assert(fileId >= 0, 'Cannot open %s.', path);
cleanup = onCleanup(@() fclose(fileId));
fprintf(fileId, '%s', content);
clear cleanup;
end
