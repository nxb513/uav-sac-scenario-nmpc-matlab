function audit_targeted_c012_context_bank()
%AUDIT_TARGETED_C012_CONTEXT_BANK Verify labels, state and curriculum coverage.

projectRoot = fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(projectRoot, 'configs'));
addpath(genpath(fullfile(projectRoot, 'src')));
cfg = targeted_lqr_weak_config();
root = fullfile(projectRoot, cfg.resultRoot, ...
    cfg.specialistBank.outputSubfolder);
artifactPath = fullfile(root, 'training_local_context_bank.mat');
assert(isfile(artifactPath), 'Context-bank artifact is missing.');
loaded = load(artifactPath, 'trainContextBank', 'trainContextManifest', ...
    'auxiliaryGrowthContextBank', 'auxiliaryGrowthContextManifest', ...
    'safeBoundaryContextBank', 'safeBoundaryContextManifest', ...
    'buildMetadata');

hard = loaded.trainContextBank;
growth = loaded.auxiliaryGrowthContextBank;
safe = loaded.safeBoundaryContextBank;
assert(all(arrayfun(@finite_context, [hard; growth; safe])), ...
    'At least one retained context has a nonfinite state or previous input.');
assert(all([hard.HardEvent]) && all([hard.PreDivergenceEligible]) && ...
    ~any([hard.GrowthOnly]), 'Hard-context labels are inconsistent.');
assert(all([growth.GrowthOnly]) && ~any([growth.HardEvent]) && ...
    ~any([growth.PreDivergenceEligible]), ...
    'Growth-only labels are inconsistent.');
assert(~any([safe.HardEvent]) && ~any([safe.GrowthOnly]), ...
    'Safe-boundary labels are inconsistent.');

currentNormalized = arrayfun(@current_normalized_error, hard);
assert(all(currentNormalized < 1 + 1e-10), ...
    'A hard context begins outside the locked C012 envelope.');
requiredReferenceStep = arrayfun(@(item) item.StartStep + ...
    cfg.specialistBank.localEpisodeSteps + ...
    cfg.specialistBank.maximumPredictionHorizon - 1, hard);
availableReferenceStep = arrayfun(@(item) size(item.Reference, 2), hard);
assert(all(requiredReferenceStep <= availableReferenceStep), ...
    'A hard context lacks the required 200+20 continuation.');

active = [hard; growth];
disturbanceType = string(arrayfun(@(item) item.Disturbance.type, active, ...
    'UniformOutput', false)).';
disturbanceLevel = arrayfun(@(item) item.Disturbance.levelIndex, active).';
contextClass = string({active.ContextClass}).';
stageCount = [nnz(disturbanceType == "zero"), ...
    nnz(disturbanceType == "zero" | disturbanceLevel == 1), ...
    nnz(ismember(disturbanceType, ...
    ["gust", "sinusoidal", "stochastic"])), ...
    nnz(contextClass == "hard_event")];
assert(all(stageCount > 0), 'At least one curriculum stage is empty.');

manifest = [loaded.trainContextManifest; ...
    loaded.auxiliaryGrowthContextManifest];
[groups, contextClassGroup, family, speed, disturbance, level, stratum] = ...
    findgroups(manifest.ContextClass, manifest.Family, ...
    manifest.TargetReferenceSpeed, manifest.DisturbanceType, ...
    manifest.DisturbanceLevel, manifest.UncertaintyStratum);
count = splitapply(@numel, manifest.ContextIndex, groups);
distribution = table(contextClassGroup, family, speed, disturbance, ...
    level, stratum, count, 'VariableNames', {'ContextClass', 'Family', ...
    'TargetReferenceSpeed', 'DisturbanceType', 'DisturbanceLevel', ...
    'UncertaintyStratum', 'ContextCount'});
writetable(distribution, fullfile(root, ...
    'active_context_distribution.csv'));

reportPath = fullfile(root, 'context_bank_audit.md');
fileId = fopen(reportPath, 'w');
assert(fileId >= 0, 'Cannot open %s.', reportPath);
cleanup = onCleanup(@() fclose(fileId));
fprintf(fileId, '# C012 context-bank audit\n\n');
fprintf(fileId, '- Hard contexts: %d.\n', numel(hard));
fprintf(fileId, '- Growth-only auxiliary contexts: %d.\n', numel(growth));
fprintf(fileId, '- Safe-boundary audit contexts: %d.\n', numel(safe));
fprintf(fileId, '- Hard-positive factorial cells: %d/135.\n', ...
    numel(unique(loaded.trainContextManifest.CellId)));
fprintf(fileId, '- Maximum normalized current C012 error: %.9f.\n', ...
    max(currentNormalized));
fprintf(fileId, '- Maximum required/available reference step: %d/%d.\n', ...
    max(requiredReferenceStep), min(availableReferenceStep));
fprintf(fileId, ['- Curriculum active contexts by stage: ' ...
    '`[%d,%d,%d,%d]`.\n'], stageCount);
fprintf(fileId, ['\nStages 1-3 may use explicitly labeled growth-only ' ...
    'boundary contexts. Stage 4 uses hard-event contexts only. Growth-only ' ...
    'is never relabeled as hard failure or used as a hard confidence target.\n']);
clear cleanup;

write_text(fullfile(root, 'AUDIT_COMPLETED.txt'), sprintf( ...
    ['status=passed\nhard_contexts=%d\ngrowth_only_contexts=%d\n' ...
    'safe_boundary_contexts=%d\nmax_current_normalized=%.12f\n' ...
    'curriculum_stage_counts=%d,%d,%d,%d\n'], numel(hard), ...
    numel(growth), numel(safe), max(currentNormalized), stageCount));
fprintf(['C012 context-bank audit passed: hard=%d, growth=%d, safe=%d, ' ...
    'stages=[%d %d %d %d].\n'], numel(hard), numel(growth), ...
    numel(safe), stageCount);
end

function yes = finite_context(item)
yes = all(isfinite(item.X0)) && all(isfinite(item.PreviousInput));
end

function value = current_normalized_error(item)
error = nmpc_state_error(item.X0, item.Reference(:, item.StartStep));
value = max([norm(error(1:3)) / 0.10, ...
    norm(error(4:6)) / deg2rad(5), norm(error(7:9)) / 0.30, ...
    norm(error(10:12)) / 2.0]);
end

function write_text(path, content)
fileId = fopen(path, 'w');
assert(fileId >= 0, 'Cannot open %s.', path);
cleanup = onCleanup(@() fclose(fileId));
fprintf(fileId, '%s', content);
clear cleanup;
end
